    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtUsername.getText().trim();
        String password = new String(txtPassword.getPassword()).trim();

        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter both username and password!");
            return;
        }

        try {
            java.sql.Connection con = com.quickmart.db.DBConnection.getConnection();
            String sql = "SELECT * FROM users WHERE username=? AND password=?";
            java.sql.PreparedStatement pst = con.prepareStatement(sql);
            pst.setString(1, username);
            pst.setString(2, password);

            java.sql.ResultSet rs = pst.executeQuery();

            if (rs.next()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Login Successful! Welcome " + username);
                new DashboardFrame().setVisible(true); // <-- THIS LINE OPENS THE DASHBOARD
                this.dispose();
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Invalid Username or Password!", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnLoginActionPerformed

